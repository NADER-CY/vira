#!/usr/bin/env python3
"""Generates platform token files from design/tokens/vira.tokens.json (doc 09 §2, DS-02).

Outputs (committed; CI runs --check and fails if they are stale):
  web/shared/src/styles/tokens.css           CSS custom properties, light + dark ([data-theme])
  mobile/lib/core/theme/tokens.g.dart        Dart constants for the Flutter ThemeData / ThemeExtension
Also fails if any foreground/background pair in CONTRAST_PAIRS is below WCAG AA (4.5:1).
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "design/tokens/vira.tokens.json")
CONTRAST_PAIRS = [("onPrimary", "primary"), ("onSurface", "surface"), ("onSurface", "background"),
                  ("onSurfaceVariant", "surface"), ("primary", "surface"), ("onPrimaryContainer", "primaryContainer"),
                  ("success", "surface"), ("danger", "surface"), ("info", "surface"), ("warning", "surface")]

def kebab(s): return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), s)

def lum(hex_):
    h = hex_.lstrip("#")[:6]
    rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]

def contrast(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)

def css(t):
    out = ["/* GENERATED by scripts/gen_tokens.py from design/tokens/vira.tokens.json — do not edit. */", ":root {"]
    out.append(f"  --font-family: '{t['font']['family']}', Tahoma, sans-serif;")
    for k, v in t["type"].items():
        out.append(f"  --type-{kebab(k)}: {v['weight']} {v['size']}px/{v['line']}px var(--font-family);")
    for k, v in t["space"].items():
        out.append(f"  --space-{k}: {v}px;")
    for k, v in t["radius"].items():
        out.append(f"  --radius-{k}: {v}px;")
    for k, v in t["motion"].items():
        out.append(f"  --motion-{k}: {v}ms;")
    out.append(f"  --min-target: {t['minTarget']}px;")
    g = t["gradient"]["brand"]
    out.append(f"  --gradient-brand: linear-gradient(135deg, {g[0]}, {g[1]});")
    out.append("}")
    for scheme in ("light", "dark"):
        sel = ":root, [data-theme='light']" if scheme == "light" else "[data-theme='dark']"
        out.append(f"{sel} {{")
        out.append(f"  color-scheme: {scheme};")
        for k, v in t["color"][scheme].items():
            out.append(f"  --color-{kebab(k)}: {v};")
        out.append("}")
    return "\n".join(out) + "\n"

def dart_color(h):
    h = h.lstrip("#")
    if len(h) == 6:
        h += "FF"
    rgb, a = h[:6], h[6:]
    return f"Color(0x{a.upper()}{rgb.upper()})"

def dart(t):
    out = ["// GENERATED by scripts/gen_tokens.py from design/tokens/vira.tokens.json — do not edit.",
           "// ignore_for_file: public_member_api_docs", "", "import 'package:flutter/painting.dart';", ""]
    for scheme in ("light", "dark"):
        cls = "ViraLightColors" if scheme == "light" else "ViraDarkColors"
        out.append(f"abstract final class {cls} {{")
        for k, v in t["color"][scheme].items():
            out.append(f"  static const {k} = {dart_color(v)};")
        out.append("}")
        out.append("")
    g = t["gradient"]["brand"]
    out.append("abstract final class ViraTokens {")
    out.append(f"  static const fontFamily = '{t['font']['family']}';")
    out.append(f"  static const gradientBrand = [{dart_color(g[0])}, {dart_color(g[1])}];")
    for k, v in t["space"].items():
        out.append(f"  static const double space{k} = {v};")
    for k, v in t["radius"].items():
        out.append(f"  static const double radius{k[0].upper() + k[1:]} = {v};")
    for k, v in t["motion"].items():
        out.append(f"  static const motion{k[0].upper() + k[1:]} = Duration(milliseconds: {v});")
    out.append(f"  static const double minTarget = {t['minTarget']};")
    out.append("}")
    out.append("")
    out.append("/// Type scale (size, line height, weight) — doc 09 §2.1.")
    out.append("abstract final class ViraTypeScale {")
    for k, v in t["type"].items():
        out.append(f"  static const {k} = (size: {v['size']}.0, height: {v['line'] / v['size']:.4f}, weight: {v['weight']});")
    out.append("}")
    return "\n".join(out) + "\n"

def main():
    t = json.load(open(SRC, encoding="utf-8"))
    bad = []
    for scheme in ("light", "dark"):
        c = t["color"][scheme]
        for fg, bg in CONTRAST_PAIRS:
            r = contrast(c[fg], c[bg])
            if r < 4.5:
                bad.append(f"{scheme}: {fg} on {bg} = {r:.2f}:1 (< 4.5)")
    if bad:
        print("WCAG AA contrast failures:\n  " + "\n  ".join(bad))
        sys.exit(1)
    outputs = {"web/shared/src/styles/tokens.css": css(t), "mobile/lib/core/theme/tokens.g.dart": dart(t)}
    stale = []
    for rel, content in outputs.items():
        path = os.path.join(ROOT, rel)
        if "--check" in sys.argv:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != content:
                stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(content)
    if stale:
        print("stale generated token files (run python3 scripts/gen_tokens.py):", ", ".join(stale))
        sys.exit(1)
    print("tokens ok" if "--check" in sys.argv else "tokens written")

if __name__ == "__main__":
    main()
