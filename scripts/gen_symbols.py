#!/usr/bin/env python3
"""Material Symbols Outlined for the mobile app (the icon font the UI archive uses).

  python3 scripts/gen_symbols.py <path to MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].ttf>
      writes mobile/assets/fonts/MaterialSymbolsOutlined.ttf (variable-font subset with only the listed glyphs,
      FILL/wght/GRAD/opsz axes kept) and mobile/lib/core/theme/symbols.g.dart
  python3 scripts/gen_symbols.py --check
      fails if symbols.g.dart does not list exactly the names in design/icons/mobile-symbols.txt (CI; no font needed)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = os.path.join(ROOT, "design/icons/mobile-symbols.txt")
DART = os.path.join(ROOT, "mobile/lib/core/theme/symbols.g.dart")
FONT = os.path.join(ROOT, "mobile/assets/fonts/MaterialSymbolsOutlined.ttf")

def names():
    out = []
    for line in open(NAMES, encoding="utf-8"):
        if not line.startswith("#"):
            out += line.split()
    return sorted(set(out))

def camel(n):
    p = n.split("_")
    s = p[0] + "".join(x.capitalize() for x in p[1:])
    return {"public": "publicIcon", "switch": "switchIcon"}.get(s, s)

def main():
    want = names()
    if "--check" in sys.argv:
        have = sorted(re.findall(r"// (\S+)\n", open(DART, encoding="utf-8").read()))
        if have != want:
            print("symbols.g.dart is stale: run scripts/gen_symbols.py with the source font")
            sys.exit(1)
        print("symbols ok")
        return
    from fontTools.ttLib import TTFont
    from fontTools import subset
    src = sys.argv[1]
    cps = {}
    for line in open(re.sub(r"\.ttf$", ".codepoints", src), encoding="utf-8"):
        n, cp = line.split()
        cps[n] = int(cp, 16)
    missing = [n for n in want if n not in cps]
    if missing:
        sys.exit(f"unknown symbols: {missing}")
    opts = subset.Options()
    opts.layout_features = []
    opts.notdef_outline = True
    opts.name_IDs = ["*"]
    font = TTFont(src)
    s = subset.Subsetter(opts)
    s.populate(unicodes=[cps[n] for n in want])
    s.subset(font)
    font.save(FONT)
    out = ["// GENERATED by scripts/gen_symbols.py from design/icons/mobile-symbols.txt — do not edit.",
           "// ignore_for_file: public_member_api_docs, constant_identifier_names", "",
           "import 'package:flutter/widgets.dart';", "",
           "/// Material Symbols Outlined (variable: FILL, wght, GRAD, opsz) — the icon set of the UI archive.",
           "/// Use with [Icon]; `fill: 1` gives the archive's `font-variation-settings: 'FILL' 1`.",
           "abstract final class Sym {"]
    for n in want:
        out.append(f"  // {n}\n  static const {camel(n)} = IconData(0x{cps[n]:x}, fontFamily: 'MaterialSymbolsOutlined', matchTextDirection: false);")
    out.append("}")
    open(DART, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"{len(want)} symbols; font {os.path.getsize(FONT)} bytes")

if __name__ == "__main__":
    main()
