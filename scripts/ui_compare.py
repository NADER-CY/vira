#!/usr/bin/env python3
"""Reference-vs-implementation sheets for the Phase 2 mobile screens (UI lock, P2 instruction §2).

For every Phase 2 screen and theme, puts the original archive screenshot (left) next to the Flutter golden
rendered in CI (right) at the same width, and writes docs/progress/P2-ui/<screen>_<theme>.jpg plus an index.

Usage: python3 scripts/ui_compare.py <archive mobile dir> <goldens dir> [out dir]
The archive is read only; nothing in it is modified.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw

# screen -> (light reference, dark reference). Where the archive has a single theme, that screen is used for
# both columns and the sheet says so (conflicts OD-P2-xx are listed in docs/progress/P2.md).
REFS = {
    "welcome": ("otp", "otp"),
    "otp": ("mobile_otp_verification_light", "mobile_otp_verification_light"),
    "home": ("home_feed_light", "_33"),
    "explore": ("_26", "_26"),
    "profile": ("user_profile_light", "user_profile_light"),
    "user_profile": ("user_profile_light", "user_profile_light"),
    "edit_profile": ("_17", "_17"),
    "followers": ("_109", "_109"),
    "post_detail": ("home_feed_light", "_33"),
    "comments": ("comments", "comments"),
    "create_post": ("create_post_light", "create_post_light"),
    "activity": ("_12", "_12"),
    "settings": ("account_settings_light", "_64"),
    "privacy": ("_125", "_46"),
    "security": ("_205", "_77"),
    "account": ("_206", "_53"),
    "report": ("_213", "_210"),
}
W = 390  # each column, px


def fit(img: Image.Image, h: int) -> Image.Image:
    img = img.convert("RGB")
    img = img.resize((W, round(img.height * W / img.width)), Image.LANCZOS)
    return img.crop((0, 0, W, min(h, img.height)))


def main() -> None:
    ref_dir, gold_dir = Path(sys.argv[1]), Path(sys.argv[2])
    out = Path(sys.argv[3] if len(sys.argv) > 3 else "docs/progress/P2-ui")
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for screen, (light, dark) in REFS.items():
        for theme, ref in (("light", light), ("dark", dark)):
            g = gold_dir / f"{screen}_{theme}.png"
            r = ref_dir / ref / "screen.png"
            if not g.exists() or not r.exists():
                rows.append((screen, theme, ref, "missing " + ("golden" if not g.exists() else "reference")))
                continue
            impl = Image.open(g)
            h = round(impl.height * W / impl.width)
            a, b = fit(Image.open(r), h), fit(impl, h)
            sheet = Image.new("RGB", (W * 2 + 24, h + 28), "white")
            d = ImageDraw.Draw(sheet)
            d.text((8, 8), f"reference: {ref}", fill="black")
            d.text((W + 32, 8), f"flutter: {screen} ({theme})", fill="black")
            sheet.paste(a, (8, 28))
            sheet.paste(b, (W + 16, 28))
            name = f"{screen}_{theme}.jpg"
            sheet.save(out / name, quality=82, optimize=True)
            rows.append((screen, theme, ref, f"[{name}]({name})"))
    lines = ["# Phase 2 — reference vs implementation", "",
             "Generated by `scripts/ui_compare.py` from the archive screenshots and the CI goldens.", "",
             "| Screen | Theme | Archive reference | Sheet |", "|---|---|---|---|"]
    lines += [f"| {s} | {t} | `{r}` | {x} |" for s, t, r, x in rows]
    (out / "README.md").write_text("\n".join(lines) + "\n")
    print(f"{sum(1 for x in rows if x[3].startswith('['))} sheets written to {out}")


if __name__ == "__main__":
    main()
